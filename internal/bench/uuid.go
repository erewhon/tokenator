package bench

import (
	"crypto/rand"
	"fmt"
)

// newUUID returns an RFC 4122 version-4 UUID. Claude Code accepts these via
// --session-id, which is how bench pre-assigns trial session ids.
func newUUID() string {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		panic(err) // crypto/rand failure is unrecoverable
	}
	b[6] = (b[6] & 0x0f) | 0x40 // version 4
	b[8] = (b[8] & 0x3f) | 0x80 // variant 10
	return fmt.Sprintf("%x-%x-%x-%x-%x", b[0:4], b[4:6], b[6:8], b[8:10], b[10:16])
}
